#!/usr/bin/env python3
"""Render PNG previews of every published logo into previews/ and write a
gallery page (previews/README.md) that GitHub displays.

    python scripts/make_previews.py

Standard logos are shown on off-white (#f9f8f9), white logos on logo black
(#231f20). Needs rsvg-convert (apt install librsvg2-bin).
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from openms_logo import brand  # noqa: E402
from openms_logo.presets import PRESETS, PUBLISHED  # noqa: E402

OUT = ROOT / "previews"
BACKDROP = {"": brand.PALETTE["white"][1], "-white": brand.LOGO_COLORS["black"]}
WIDTH = 600


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*.png"):
        old.unlink()
    rows = ["# Logo previews", "",
            "Generated by `python scripts/make_previews.py` from the SVGs in [`logos/`](../logos).",
            "Only **full** is the official logo. Everything else is a derived sublogo that is not yet approved.", "",
            "| Preset | Standard (light backdrop) | White (dark backdrop) |", "|---|---|---|"]
    for name in PUBLISHED:
        cells = []
        for suffix, bg in BACKDROP.items():
            svg = ROOT / "logos" / f"{name}{suffix}.svg"
            png = OUT / f"{name}{suffix}.png"
            subprocess.run(["rsvg-convert", "-w", str(WIDTH), "-b", bg, str(svg), "-o", str(png)], check=True)
            cells.append(f'<img src="{png.name}" width="300" alt="{name}{suffix}">')
        doc = " ".join((PRESETS[name].__doc__ or "").split())
        rows.append(f"| **{name}**<br>{doc} | {cells[0]} | {cells[1]} |")
    (OUT / "README.md").write_text("\n".join(rows) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
